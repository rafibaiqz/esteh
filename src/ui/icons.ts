// Original pixel-style icons drawn as inline SVG (16×16 grid, crisp edges).

type Px = [number, number, number, number, string];

function svg(px: Px[], size = 22): string {
  const body = px.map(([x, y, w, h, c]) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${c}"/>`).join('');
  return `<svg class="ico" width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${body}</svg>`;
}

